import pytest

from mintrans_stats.classify import is_bulletin


@pytest.mark.parametrize(
    "title",
    [
        "ТРАНСПОРТ РОССИИ. Информационно-статистический бюллетень. 9 месяцев 2025 года",
        "Информационно- статистический бюллетень «Транспорт России» за январь - март 2016 года",
        "ТРАНСПОРТ РОССИИ. Информационно-статистический бюллетень. Январь-декабрь 2012 года.",
    ],
)
def test_bulletin_titles(title):
    assert is_bulletin(title)


@pytest.mark.parametrize(
    "title",
    [
        "Статистический сборник «Автомобильные дороги Российской Федерации»",
        "Статистическая информация по форме федерального статистического наблюдения "
        "№ 1 - контракт «Сведения об определении поставщиков»",
        "Статистика VIII Международного форума и выставки «Транспорт России»",
        "Информационный бюллетень о порядке использования воздушного пространства",
        "Приказ Минтранса России «Об утверждении формы информационно-статистического бюллетеня»",
        "",
    ],
)
def test_not_bulletin_titles(title):
    assert not is_bulletin(title)
