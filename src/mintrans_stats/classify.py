"""Отбор выпусков бюллетеня «Транспорт России» по названию документа.

В разделе «Статистика» и в выдаче поиска кроме бюллетеня есть формы закупок, доклады,
индикаторы программ и т. п. Выпуск бюллетеня узнаётся по словам «информационно-статистический
бюллетень» в названии; нормативные акты и методики с такими словами отсекаются.
"""

from __future__ import annotations

import re

BULLETIN_RE = re.compile(r"информационно-\s*статистическ\w*\s+бюллетен", re.IGNORECASE)
EXCLUDE_RE = re.compile(
    r"^\s*(?:приказ|распоряжение|проект|постановление|методик|методическ|об\s+утверждении)",
    re.IGNORECASE,
)


def is_bulletin(title: str) -> bool:
    return bool(BULLETIN_RE.search(title or "")) and not EXCLUDE_RE.search(title or "")
